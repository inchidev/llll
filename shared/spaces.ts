import { z } from 'zod'
import { Permission } from './permissions'
import type { AuthorizationContext } from './authorization'

/** The Space every existing resource and new Member starts in. Fixed, so SQL defaults can name it. */
export const DEFAULT_SPACE_ID = '00000000-0000-4000-8000-00000000000d'
/** The Client names the Space it is showing with this header; the Server checks it against membership. */
export const SPACE_HEADER = 'x-l4-space'

/** Resources whose IDs the boundary lists, so synchronous permission checks can refuse them. */
export type SpaceDeniedKind = 'projects' | 'boards' | 'databases' | 'documents' | 'canvases' | 'gadgets' | 'connections' | 'environments' | 'agents'
export type SpaceBoundary = {
  /** Spaces this request may reach. The Server Owner is limited like everyone else. */
  ids: string[]
  /** The one Space this request works in, when it has one: new resources land here. */
  active: string | null
  /** Resources in other Spaces. Empty when the context reaches everything. */
  denied: Partial<Record<SpaceDeniedKind, ReadonlySet<string>>>
}
type Scoped = Pick<AuthorizationContext, 'spaces'>

/**
 * A context without a boundary reaches only the default Space, so a path that forgets to
 * load one still cannot read another department.
 */
export function reachableSpaceIds(auth: Scoped): string[] {
  return auth.spaces?.ids ?? [DEFAULT_SPACE_ID]
}
export function spaceAllowed(auth: Scoped, spaceId: string): boolean {
  return reachableSpaceIds(auth).includes(spaceId)
}
export function spaceResourceDenied(auth: Scoped, kind: SpaceDeniedKind, id: string): boolean {
  return Boolean(auth.spaces?.denied[kind]?.has(id))
}
/**
 * Where a new resource goes: the active Space or the only one reachable. Someone in several with
 * none chosen gets null rather than a guess, which could publish one department's work to another.
 */
export function creationSpaceId(auth: Scoped): string | null {
  const ids = reachableSpaceIds(auth)
  if (auth.spaces?.active && ids.includes(auth.spaces.active)) return auth.spaces.active
  return ids.length === 1 ? ids[0]! : null
}
/** Space IDs are generated by the Server; the check keeps this safe to inline in `IN (...)`. */
export function spaceSqlList(ids: readonly string[]): string {
  if (!ids.length) return "''"
  return ids.map(id => {
    if (!/^[0-9a-f-]{36}$/u.test(id)) throw new Error('Invalid Space ID')
    return `'${id}'`
  }).join(',')
}
export function spaceSql(auth: Scoped): string {
  return spaceSqlList(reachableSpaceIds(auth))
}

/**
 * What a Space admin may do inside their Space, whatever their Role. It holds only for a
 * request already scoped to that Space; Server settings, Roles and removal from the Server
 * stay with the Role.
 */
export const SpaceAdminPermissions = Permission.manageChannels | Permission.manageTasks | Permission.manageDatabases
  | Permission.manageGadgets | Permission.manageProjects | Permission.manageAgents | Permission.invite

export const QUOTA_FIELDS = ['storageLimitBytes', 'memberLimit', 'agentLimit', 'monthlyRunLimit', 'monthlyEmailLimit', 'monthlyVoiceLimit'] as const
export type SpaceQuotaField = typeof QUOTA_FIELDS[number]
export type SpaceQuotas = Record<SpaceQuotaField, number | null>
const limit = z.number().int().min(0).max(Number.MAX_SAFE_INTEGER).nullable()
export const spaceCreateSchema = z.object({ name: z.string().trim().min(1).max(80), description: z.string().trim().max(500).default('') }).strict()
export const spacePatchSchema = z.object({ name: z.string().trim().min(1).max(80).optional(), description: z.string().trim().max(500).optional() }).strict()
export const spaceLimitsSchema = z.object({
  storageLimitBytes: limit.optional(), memberLimit: limit.optional(), agentLimit: limit.optional(), monthlyRunLimit: limit.optional(), monthlyEmailLimit: limit.optional(), monthlyVoiceLimit: limit.optional(),
  /** Back to no limit at all. */
  reset: z.literal(true).optional(),
  actionLimits: z.record(z.string().regex(/^[a-z-]+\.[a-z-]+$/u), z.object({ limit: z.number().int().min(1).max(100_000), windowSeconds: z.number().int().min(1).max(86_400) }).strict()).optional(),
}).strict()
export const spaceMemberSchema = z.object({ userId: z.string().min(1).max(200), role: z.enum(['member', 'admin']).default('member') }).strict()
export const spaceMemberPatchSchema = z.object({ role: z.enum(['member', 'admin']) }).strict()

export type SpaceRole = 'member' | 'admin'
export type SpaceDTO = {
  id: string; name: string; description: string; isDefault: boolean
  /** The viewer's own place in it; null when the Owner manages a Space without having joined. */
  role: SpaceRole | null
  memberCount: number
  quotas?: SpaceQuotas
  /** It cannot be used until the Owner resumes it. Nothing in it is lost. */
  suspended?: boolean
}

export const SPACE_ADMIN_SORTS = ['name', 'creator', 'people', 'projects', 'tasks', 'recordings', 'storage', 'voice', 'messages', 'created', 'activity'] as const
export type SpaceAdminSort = typeof SPACE_ADMIN_SORTS[number]
const adminFilter = <T extends z.ZodTypeAny>(schema: T) => z.preprocess(value => value === '' ? undefined : value, schema.optional())
export const spaceAdminQuerySchema = z.object({
  q: adminFilter(z.string().trim().max(100)),
  sort: z.enum(SPACE_ADMIN_SORTS).default('activity'),
  dir: z.enum(['asc', 'desc']).default('desc'),
  page: z.coerce.number().int().min(1).max(1_000_000).default(1),
  pageSize: z.coerce.number().int().min(1).max(100).default(25),
  limit: adminFilter(z.enum(['near', 'over'])),
  state: adminFilter(z.enum(['inactive', 'suspended'])),
})
/** One row of the Owner's table. Counts only: nothing in it comes from what a Space holds. */
export type SpaceAdminRow = SpaceDTO & {
  creator: { name: string; email: string | null } | null
  people: number; projects: number; tasks: number; recordings: number; storageBytes: number; voiceMinutes: number; messages: number
  createdAt: string; lastActivityAt: string | null
  suspended: boolean
}
export type SpaceAdminList = { spaces: SpaceAdminRow[]; total: number; page: number; pageSize: number; refreshedAt: string }

