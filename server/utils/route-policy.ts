import type { SpaceResourceKind } from './space-access'

/**
 * How one API route relates to the Space boundary. Every file under server/api has one entry,
 * and `route-policy.test.ts` fails on a route that has none: a new route must say where it stands.
 *
 * - `unscoped`: no session involved, or its own credential (sign-in, webhooks, Run gateway).
 * - `account`: about the caller only, whichever Spaces they are in.
 * - `server`: Server administration above any Space. Its own permission check decides.
 * - `space`: one resource, named in the URL. The gate finds its Space and refuses outsiders.
 * - `active`: lists or creates inside the request's active Space. The handler filters by the boundary.
 * - `member`: about one Member, visible only to someone sharing a Space with them.
 */
export type RoutePolicy =
  | { scope: 'unscoped' | 'account' | 'server' | 'active'; action: string }
  | { scope: 'member'; param: string; action: string }
  | { scope: 'space'; resource: SpaceResourceKind; param: string; action: string }

const unscoped = (action: string): RoutePolicy => ({ scope: 'unscoped', action })
const forAccount = (action: string): RoutePolicy => ({ scope: 'account', action })
const onServer = (action: string): RoutePolicy => ({ scope: 'server', action })
const inActiveSpace = (action: string): RoutePolicy => ({ scope: 'active', action })
const memberOf = (param: string, action: string): RoutePolicy => ({ scope: 'member', param, action })
const inSpace = (resource: SpaceResourceKind, param: string, action: string): RoutePolicy => ({ scope: 'space', resource, param, action })

