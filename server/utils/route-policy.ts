type CompiledRoute = { route: string; method: string | null; segments: string[]; policy: RoutePolicy; params: Array<[number, string]>; rest: boolean }
let compiled: CompiledRoute[] | null = null

function compile(): CompiledRoute[] {
  if (compiled) return compiled
  compiled = Object.entries(ROUTE_POLICIES).map(([route, policy]) => {
    const method = route.match(/\.(get|post|put|patch|delete)$/u)?.[1]?.toUpperCase() ?? null
    const path = route.replace(/\.(get|post|put|patch|delete)$/u, '').replace(/\/index$/u, '').replace(/^index$/u, '')
    const segments = path.split('/')
    return {
      route, method, segments, policy, rest: segments.at(-1)!.startsWith('[...'),
      params: segments.flatMap((segment, index): Array<[number, string]> => /^\[[^.]/u.test(segment) ? [[index, segment.slice(1, -1)]] : []),
    }
  })
  return compiled
}

/** The policy Nitro's router would reach for this request: literal segments beat parameters. */
export function matchRoutePolicy(method: string, path: string): { policy: RoutePolicy; params: Record<string, string> } | null {
  const parts = path.replace(/^\/api\//u, '').replace(/\/$/u, '').split('/')
  let best: { route: CompiledRoute; score: number } | null = null
  for (const route of compile()) {
    if (route.method && route.method !== method && !(method === 'HEAD' && route.method === 'GET')) continue
    if (route.rest ? parts.length < route.segments.length - 1 : parts.length !== route.segments.length) continue
    let score = 0, matched = true
    for (let index = 0; index < route.segments.length && matched; index++) {
      const segment = route.segments[index]!
      if (segment.startsWith('[...')) break
      if (segment.startsWith('[')) score += 1
      else if (segment === parts[index]) score += 2
      else matched = false
    }
    if (!matched) continue
    // A rest route is the router's last resort.
    if (route.rest) score -= 1
    if (!best || score > best.score) best = { route, score }
  }
  if (!best) return null
  return { policy: best.route.policy, params: Object.fromEntries(best.route.params.map(([index, name]) => [name, decodeURIComponent(parts[index] ?? '')])) }
}
