#!/usr/bin/env node
// Copies PartyPortal's guest page into the Server (ADR 0014) and regenerates the module that serves it.
// Usage: node scripts/sync-portal-guest.mjs [path/to/partyportal/web/guest.html]
// Without a path it only regenerates the module from server/assets/portal-guest.html.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('..', import.meta.url))
const asset = `${root}server/assets/portal-guest.html`
const source = process.argv[2]
if (source) writeFileSync(asset, readFileSync(source, 'utf8'))
const html = readFileSync(asset, 'utf8')
writeFileSync(`${root}server/utils/portal-guest-page.ts`, `// Generated by scripts/sync-portal-guest.mjs from server/assets/portal-guest.html. Do not edit.
export const PORTAL_GUEST_HTML: string = ${JSON.stringify(html)}
`)
console.log(`portal guest page: ${html.length} bytes`)
